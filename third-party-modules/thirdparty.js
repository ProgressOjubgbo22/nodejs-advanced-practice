// ================= Working with npm (Third-Party Modules) =================

// Import a third-party package (example: lodash)
const _ = require("lodash");

// Using lodash to capitalize a string
const name = "ojugbo";
console.log("Capitalized:", _.capitalize(name)); // Ojugbo

// Notes: 
// 1. Make sure to run `npm init -y` to create package.json
// 2. Install lodash using: npm install lodash
